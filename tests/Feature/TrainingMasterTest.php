    public function test_company_document_update_triggers_scoped_training_announcements(): void
    {
        config(['scout.driver' => null]);

        $dept = Department::create(['name' => 'Operations Dept ' . uniqid()]);
        $pos = OfficePosition::create(['name' => 'Branch Manager']);

        $training = Training::create([
            'code' => 'OP-WORKFLOW-' . uniqid(),
            'title' => 'Branch Operations SOP',
            'retrain_interval' => 12,
            'retrain_unit' => 'month',
            'passing_score' => 80.00,
            'status' => 'active',
        ]);

        TrainingScope::create([
            'training_id' => $training->id,
            'department_id' => $dept->id,
            'office_position_id' => $pos->id,
        ]);

        $permPos = \App\Models\Position::firstOrCreate(['name' => 'General Staff']);
        $branch = \App\Models\Branch::firstOrCreate(['name' => 'HQ Branch']);
        $location = \App\Models\Location::firstOrCreate(['name' => 'HQ Location']);

        $user = User::create([
            'name' => 'Manager Bob',
            'email' => 'bob.' . uniqid() . '@example.com',
            'password' => bcrypt('password'),
            'position_id' => $permPos->id,
            'branch_id' => $branch->id,
            'location_id' => $location->id,
            'department_id' => $dept->id,
            'office_position_id' => $pos->id,
        ]);

        $type = \App\Models\CompanyDocumentType::firstOrCreate(['name' => 'Standard SOP']);
        $doc = \App\Models\CompanyDocument::create([
            'title' => 'Branch Operations Manual',
            'body' => '<p>Initial version</p>',
            'department_id' => $dept->id,
            'company_document_type_id' => $type->id,
            'created_by' => $user->id,
            'updated_by' => $user->id,
        ]);

        // Connect document to training
        $training->companyDocuments()->attach($doc->id);
        $this->assertTrue($training->companyDocuments()->where('company_documents.id', $doc->id)->exists());
        $this->assertTrue($doc->trainings()->where('trainings.id', $training->id)->exists());

        // Update document with training_required trigger via controller
        $this->actingAs($user)->put(route('document.library.update', $doc->id), [
            'title' => 'Branch Operations Manual V2',
            'body' => '<p>Updated settlement rules</p>',
            'department_id' => $dept->id,
            'company_document_type_id' => $type->id,
            'training_required' => true,
            'training_ids' => [$training->id],
            'training_reason' => 'Settlement rules updated in V2',
        ]);

        // Assert trigger was created and user in scope was assigned
        $this->assertDatabaseHas('training_triggers', [
            'training_id' => $training->id,
            'trigger_type' => 'WORKFLOW_CHANGE',
            'reason' => 'Settlement rules updated in V2',
        ]);

        $this->assertDatabaseHas('training_assignments', [
            'training_id' => $training->id,
            'user_id' => $user->id,
            'status' => 'PENDING',
        ]);
    }

    public function test_department_wide_training_scope_affects_all_department_users_and_position_specific_scope_only_affects_position(): void
    {
        $dept = Department::create(['name' => 'HR Department ' . uniqid()]);
        $posManager = OfficePosition::create(['name' => 'HR Manager ' . uniqid()]);
        $posOfficer = OfficePosition::create(['name' => 'HR Officer ' . uniqid()]);
        $cat = TrainingCategory::create(['name' => 'General Policy ' . uniqid()]);

        // 1. Training A: Scoped to entire HR Department (office_position_id = null)
        $trainingDeptWide = Training::create([
            'code' => 'HR-ALL-' . uniqid(),
            'title' => 'HR General Conduct',
            'training_category_id' => $cat->id,
            'retrain_interval' => 12,
            'retrain_unit' => 'month',
            'passing_score' => 80.00,
            'status' => 'active',
        ]);
        TrainingScope::create([
            'training_id' => $trainingDeptWide->id,
            'department_id' => $dept->id,
            'office_position_id' => null,
        ]);

        // 2. Training B: Scoped strictly to HR Manager in HR Dept
        $trainingManagerOnly = Training::create([
            'code' => 'HR-MGR-' . uniqid(),
            'title' => 'HR Management Advanced SOP',
            'training_category_id' => $cat->id,
            'retrain_interval' => 12,
            'retrain_unit' => 'month',
            'passing_score' => 80.00,
            'status' => 'active',
        ]);
        TrainingScope::create([
            'training_id' => $trainingManagerOnly->id,
            'department_id' => $dept->id,
            'office_position_id' => $posManager->id,
        ]);

        $permPos = \App\Models\Position::firstOrCreate(['name' => 'General Staff']);
        $branch = \App\Models\Branch::firstOrCreate(['name' => 'HQ Branch']);
        $location = \App\Models\Location::firstOrCreate(['name' => 'HQ Location']);

        // User 1: HR Manager (should receive both trainings)
        $user1 = User::create([
            'name' => 'HR Manager User',
            'email' => 'hr.mgr.' . uniqid() . '@example.com',
            'password' => bcrypt('password'),
            'position_id' => $permPos->id,
            'branch_id' => $branch->id,
            'location_id' => $location->id,
            'department_id' => $dept->id,
            'office_position_id' => $posManager->id,
        ]);

        // User 2: HR Officer (should receive department-wide training only)
        $user2 = User::create([
            'name' => 'HR Officer User',
            'email' => 'hr.officer.' . uniqid() . '@example.com',
            'password' => bcrypt('password'),
            'position_id' => $permPos->id,
            'branch_id' => $branch->id,
            'location_id' => $location->id,
            'department_id' => $dept->id,
            'office_position_id' => $posOfficer->id,
        ]);

        // User 3: Employee in another department (should receive neither)
        $otherDept = Department::create(['name' => 'IT Dept ' . uniqid()]);
        $user3 = User::create([
            'name' => 'IT User',
            'email' => 'it.user.' . uniqid() . '@example.com',
            'password' => bcrypt('password'),
            'position_id' => $permPos->id,
            'branch_id' => $branch->id,
            'location_id' => $location->id,
            'department_id' => $otherDept->id,
            'office_position_id' => $posManager->id,
        ]);

        // Assert User 1 (Manager) got both trainings
        $this->assertDatabaseHas('training_assignments', [
            'training_id' => $trainingDeptWide->id,
            'user_id' => $user1->id,
        ]);
        $this->assertDatabaseHas('training_assignments', [
            'training_id' => $trainingManagerOnly->id,
            'user_id' => $user1->id,
        ]);

        // Assert User 2 (Officer) got department-wide training, but NOT the manager-only training
        $this->assertDatabaseHas('training_assignments', [
            'training_id' => $trainingDeptWide->id,
            'user_id' => $user2->id,
        ]);
        $this->assertDatabaseMissing('training_assignments', [
            'training_id' => $trainingManagerOnly->id,
            'user_id' => $user2->id,
        ]);

        // Assert User 3 (Other department) got neither
        $this->assertDatabaseMissing('training_assignments', [
            'training_id' => $trainingDeptWide->id,
            'user_id' => $user3->id,
        ]);
        $this->assertDatabaseMissing('training_assignments', [
            'training_id' => $trainingManagerOnly->id,
            'user_id' => $user3->id,
        ]);
    }

