    public function test_test_evaluation_failing_and_passing_flows(): void
    {
        $code = 'FIN-CASH-' . uniqid();
        $dept = Department::create(['name' => 'Finance Dept ' . uniqid()]);
        $pos = OfficePosition::create(['name' => 'Cashier']);

        $training = Training::create([
            'code' => $code,
            'title' => 'Cash Handling SOP',
            'retrain_interval' => 6,
            'retrain_unit' => 'month',
            'passing_score' => 80.00,
            'status' => 'active',
        ]);

        $test = Test::create([
            'training_id' => $training->id,
            'title' => 'Cash SOP Test',
            'passing_score' => 80.00,
            'status' => 'active',
        ]);

        // Add 2 questions: Q1 (50 pts), Q2 (50 pts)
        $q1 = TestQuestion::create([
            'test_id' => $test->id,
            'question' => 'Always verify cash before delivery?',
            'question_type' => 'TRUE_FALSE',
            'marks' => 50,
            'sort_order' => 1,
        ]);
        $q1OptTrue = TestOption::create(['test_question_id' => $q1->id, 'answer' => 'True', 'is_correct' => true]);
        $q1OptFalse = TestOption::create(['test_question_id' => $q1->id, 'answer' => 'False', 'is_correct' => false]);

        $q2 = TestQuestion::create([
            'test_id' => $test->id,
            'question' => 'Where should currency balance be logged?',
            'question_type' => 'MULTIPLE_CHOICE',
            'marks' => 50,
            'sort_order' => 2,
        ]);
        $q2OptA = TestOption::create(['test_question_id' => $q2->id, 'answer' => 'Cash Register Book', 'is_correct' => false]);
        $q2OptB = TestOption::create(['test_question_id' => $q2->id, 'answer' => 'ERP System', 'is_correct' => true]);

        $permPos = \App\Models\Position::firstOrCreate(['name' => 'General Staff']);
        $branch = \App\Models\Branch::firstOrCreate(['name' => 'HQ Branch']);
        $location = \App\Models\Location::firstOrCreate(['name' => 'HQ Location']);

        $user = User::create([
            'name' => 'Alice Cashier',
            'email' => 'alice.' . uniqid() . '@example.com',
            'password' => bcrypt('password'),
            'position_id' => $permPos->id,
            'branch_id' => $branch->id,
            'location_id' => $location->id,
            'department_id' => $dept->id,
            'office_position_id' => $pos->id,
        ]);

        $assignment = TrainingAssignment::create([
            'training_id' => $training->id,
            'user_id' => $user->id,
            'status' => 'PENDING',
        ]);

        $session = TrainingSession::create([
            'training_id' => $training->id,
            'session_code' => 'FIN-CASH-S001',
            'title' => 'Session #1',
            'status' => 'OPEN',
        ]);

        $participant = TrainingSessionParticipant::create([
            'training_session_id' => $session->id,
            'training_assignment_id' => $assignment->id,
            'user_id' => $user->id,
            'attendance_status' => 'REGISTERED',
        ]);

        $evalService = app(TestEvaluationService::class);

        // Attempt 1: Failed (Q1 correct, Q2 wrong => 50% < 80%)
        $attempt1 = $evalService->startAttempt($test, $user, $assignment, $session->id);
        $res1 = $evalService->submitAttempt($attempt1, [
            $q1->id => $q1OptTrue->id,
            $q2->id => $q2OptA->id,
        ]);

        $this->assertEquals('FAILED', $res1['attempt']->result);
        $this->assertEquals(50.0, $res1['percentage']);
        $this->assertFalse($res1['passed']);

        // Check that Session #2 was automatically provisioned as PENDING
        $this->assertDatabaseHas('training_sessions', [
            'training_id' => $training->id,
            'status' => 'PENDING',
        ]);

        // Now mark session attendance as ATTENDED for Tier 1 requirement
        $participant->update(['attendance_status' => 'ATTENDED']);

        // Attempt 2: Passed (Q1 correct, Q2 correct => 100% >= 80%)
        $attempt2 = $evalService->startAttempt($test, $user, $assignment, $session->id);
        $res2 = $evalService->submitAttempt($attempt2, [
            $q1->id => $q1OptTrue->id,
            $q2->id => $q2OptB->id,
        ]);

        $this->assertEquals('PASSED', $res2['attempt']->result);
        $this->assertEquals(100.0, $res2['percentage']);
        $this->assertTrue($res2['passed']);
        $this->assertTrue($res2['requirement_completed']);

        // Check assignment is now marked COMPLETED with completed_at
        $assignment->refresh();
        $this->assertEquals('COMPLETED', $assignment->status);
        $this->assertNotNull($assignment->completed_at);
    }

